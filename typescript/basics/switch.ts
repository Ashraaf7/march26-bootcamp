let browser = "safari";

switch (browser) {
    case "chrome":
        console.log("you are using chrome browser");
        break;

    case "edge":
        console.log("you are using edge browser");
        break;

    case "firefox":
        console.log("you are using firefox browser");
        break;

    default:
        console.log("you are using an unsupported browser");
}